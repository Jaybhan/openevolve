def kill(m, n, s, t, w, rows, cols):
    """Python mirror of candidate.kill (library part mirrors ZarPrune.counting)."""
    if sum(comb(c, s) for c in cols) > (t - 1) * comb(m, s):
        return True                                                   # argA
    if sum(comb(r, t) for r in rows) > (s - 1) * comb(n, t):
        return True                                                   # argAT
    if s >= 1:
        Bc = (t - 1) * comb(m, s)
        if sum(cols) > waterfill_bound(m, n, s, Bc):
            return True
    if t >= 1:
        Br = (s - 1) * comb(n, t)
        if sum(rows) > waterfill_bound(n, m, t, Br):
            return True
    r0, c0 = rows[0], cols[0]
    if r0 and sum(comb(c - 1, s - 1) for c in sorted(cols)[:r0] if c) > (t - 1) * comb(m - 1, s - 1):
        return True                                                   # argD
    if c0 and sum(comb(r - 1, t - 1) for r in sorted(rows)[:c0] if r) > (s - 1) * comb(n - 1, t - 1):
        return True                                                   # argDT
    return False                                                      # your prunes go above


def waterfill_bound(m, n, s, budget):
    """Maximum total degree with n entries bounded by m and
    total choose(s) cost at most budget."""
    if s == 0:
        return m * n
    values = sorted(range(m + 1), key=lambda x: (comb(x, s), x))
    best = 0
    for q in range(n + 1):
        for d in values:
            cost = q * comb(d, s)
            if cost <= budget:
                total = q * d
                if total > best:
                    best = total
    return best
