"""E25 step 1: the candidate-program benchmark (experiments/E25_reward/candidates/*.py).

Every generated program follows initial_program.py's structure (NOTES, LEAN_SOURCE, SCHEMA_DATA,
kill) and is a legal evolved program: its Lean is checked by the real gate in compute_masks.py,
its Python `kill` is a sound mirror of the Lean kill (library + DGH mirror; the evaluator adds
the schema mirror itself).  Certificates come from results/cert_pool.json (cert_pool.py) and
results/recipe_certs_frozen.json (search_certificates run to completion, identical to the 40 s run).

Copied verbatim from tests/candidates/: initial, lean_dgh4, schema_recipe (dynamic; scored through
its frozen twin schema_recipe_frozen), instance_specific.
"""
from __future__ import annotations

import json
import os
import shutil

_HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(_HERE))
OUT = os.path.join(_HERE, "candidates")
TEMPLATE = os.path.join(ROOT, "tests", "candidates", "initial.py")

WEAK_MAX_GAIN = 0.16  # f_weak: skip cells whose weakest certificate removes more than this share
LIB_RETURN = "    return False                                                      # your prunes go above"

DGH_PY = '''
def _dgh_col_kill(m, s, t, cols):
    """Mirror of ZarPrune.argDGHCol (DGH v = s-1, all k in [s, m]); copied from tests/candidates/lean_dgh4.py."""
    if s < 1:
        return False
    v = s - 1
    R = (t - 1) * (m - s + 1)
    ch = [comb(c, v) for c in cols]
    S = sum(ch)
    Cm = comb(m, v)
    for k in range(s, m + 1):
        D = k - s + 1
        a, c = R % D, R // D
        if (D - a) * S > (D - a) * c * Cm + sum((k - cj) * chj for cj, chj in zip(cols, ch) if cj < k):
            return True
    return False


def _dgh_kill(m, n, s, t, w, rows, cols):
    return _dgh_col_kill(m, s, t, cols) or _dgh_col_kill(n, t, s, rows)

'''

LEAN_TMPL = """
/-- {doc} -/
def candidate (P : Params) : Prune P :=
  {body}
"""


def _template() -> tuple:
    src = open(TEMPLATE).read()
    # strip the golden docstring header (first triple-quoted block) and keep the program docstring
    first = src.find('"""', 3) + 3
    body = src[first:]
    return src, body


def build(name: str, doc: str, lean_body: str, lean_doc: str, schema: dict, extra_py: str = "",
          extra_return: str = "", notes: str = "") -> str:
    src = open(TEMPLATE).read()
    # 1) golden header -> E25 header
    end_hdr = src.find('"""', 3) + 3
    src = f'"""[E25 CANDIDATE `{name}`] {doc}\n\nGenerated by experiments/E25_reward/make_candidates.py from ' \
          f'tests/candidates/initial.py; do not edit by hand.' + src[src.find("\n\nPrune library"):end_hdr - 3] + '"""' + src[end_hdr:]
    # 2) NOTES
    a = src.index('NOTES = r"""')
    b = src.index('"""', a + len('NOTES = r"""')) + 3
    src = src[:a] + 'NOTES = r"""' + (notes or doc).replace('"""', "'''") + '"""' + src[b:]
    # 3) LEAN_SOURCE
    a = src.index("LEAN_SOURCE = r'''")
    b = src.index("'''", a + len("LEAN_SOURCE = r'''")) + 3
    src = src[:a] + "LEAN_SOURCE = r'''" + LEAN_TMPL.format(doc=lean_doc, body=lean_body) + "'''" + src[b:]
    # 4) SCHEMA_DATA
    a = src.index("SCHEMA_DATA = ")
    b = src.index("\n", a)
    src = src[:a] + "SCHEMA_DATA = " + json.dumps(schema, separators=(",", ":")) + src[b:]
    # 5) python mirror of the extra prune
    if extra_py:
        a = src.index("\ndef kill(")
        src = src[:a] + "\n" + extra_py + src[a:]
    if extra_return:
        assert LIB_RETURN in src
        src = src.replace(LIB_RETURN, "    return " + extra_return)
    return src


def main():
    os.makedirs(OUT, exist_ok=True)
    pool = json.load(open(os.path.join(_HERE, "results", "cert_pool.json")))
    frozen = json.load(open(os.path.join(_HERE, "results", "recipe_certs_frozen.json")))

    def certs_of(pred):
        out, seen = [], set()
        for key in sorted(pool):
            v = pool[key]
            for c in v["certs"]:
                if pred(key, v, c):
                    k = (v["m"], v["n"], v["s"], v["t"], tuple(c["y"]))
                    if k not in seen:
                        seen.add(k)
                        out.append({"m": v["m"], "n": v["n"], "s": v["s"], "t": v["t"], "y": c["y"]})
        return out

    def sch(certs):
        return {"farkas": certs, "residue": [], "prefix": []}

    def gain_of(v, c):
        d = {int(i): x for i, x in v["d"].items()}
        W = sum(d.values()) or 1.0
        return sum(d[j] for j in c["kills"]) / W

    import sys as _sys
    _sys.path.insert(0, ROOT)
    _sys.path.insert(0, _HERE)
    import universe as U  # noqa: E402
    from zar_ub import reward as _reward  # noqa: E402
    _cens = {}

    def censored(key, i):
        if key not in _cens:
            tab = U.load(key)
            _cens[key] = [_reward.is_censored(r) for r in tab.records]
        return _cens[key][i]

    def easy_only(key, v, c):
        """every kill is EXACTLY labelled (not censored) and has d <= the table's median survivor d."""
        d = {int(i): x for i, x in v["d"].items()}
        ds = sorted(d.values())
        med = ds[len(ds) // 2]
        if any(censored(key, j) for j in c["kills"]):
            return False
        return max(d[j] for j in c["kills"]) <= med

    # the weakest certificate of every (3,3) cell (one per cell): a general, weak rule
    weakest = {}
    for key in sorted(pool):
        v = pool[key]
        if (v["s"], v["t"]) != (3, 3) or not v["certs"]:
            continue
        c = min(v["certs"], key=lambda c: (gain_of(v, c), c["case"]))
        if gain_of(v, c) > WEAK_MAX_GAIN:  # the cell has no weak certificate (e.g. (10,22): its only one closes it)
            continue
        weakest[(v["m"], v["n"])] = {"m": v["m"], "n": v["n"], "s": 3, "t": 3, "y": c["y"]}

    lib = "Prune.ofList P [counting P, examplePrune P]"
    progs = {
        "schema_recipe_frozen": dict(
            doc="schema_recipe with its SCHEMA_DATA frozen: the 34 certificates search_certificates(max_seconds=40) "
                "returns on the current cache (run to completion; identical to an unbounded run).",
            schema=sch(frozen)),
        "schema_pool": dict(
            doc="every Farkas certificate of the E25 pool (all LP-refutable library survivors of every universe "
                "table): the best any SCHEMA_DATA-only program can do on these tables.",
            schema=sch(certs_of(lambda k, v, c: True))),
        "dgh_lib": dict(
            doc="counting + the library's argDGH (same kill as lean_dgh4, without re-proving DGH).",
            lean_body="Prune.ofList P [counting P, argDGH P]", lean_doc="counting + DGH (library argDGH)",
            extra_py=DGH_PY, extra_return="_dgh_kill(m, n, s, t, w, rows, cols)"),
        "recipe_dgh": dict(
            doc="schema_recipe_frozen + argDGH: the program luna wrote at iteration 1 of E21.",
            lean_body="Prune.ofList P [counting P, argDGH P]", lean_doc="counting + DGH, plus the recipe certificates",
            extra_py=DGH_PY, extra_return="_dgh_kill(m, n, s, t, w, rows, cols)", schema=sch(frozen)),
        "cert_one_train": dict(
            doc="single-cell specialist: every pool certificate of the TRAIN cell (10,11;3,3) and nothing else.",
            schema=sch(certs_of(lambda k, v, c: (v["m"], v["n"], v["s"], v["t"]) == (10, 11, 3, 3)))),
        "cert_target_12_18": dict(
            doc="single-TARGET specialist: every pool certificate tagged (12,18;3,3) (default target w=109).",
            schema=sch(certs_of(lambda k, v, c: (v["m"], v["n"], v["s"], v["t"]) == (12, 18, 3, 3)))),
        "inst_dgh_10_23": dict(
            doc="instance-specific prune: argDGH only when P = (10,23,*) (target_x (10,23,113)); kills survivors of "
                "that one table only.",
            lean_body="if P.m = 10 ∧ P.n = 23 then Prune.ofList P [counting P, argDGH P] else counting P",
            lean_doc="DGH restricted to (m,n) = (10,23)",
            extra_py=DGH_PY, extra_return="(m == 10 and n == 23 and _dgh_kill(m, n, s, t, w, rows, cols))"),
        "cert_close_10_22": dict(
            doc="single-cell specialist that CLOSES a small table: the one pool certificate tagged (10,22;3,3), "
                "which kills all 3 library survivors of (10,22,111) (tan2022).",
            schema=sch(certs_of(lambda k, v, c: (v["m"], v["n"], v["s"], v["t"]) == (10, 22, 3, 3)))),
        "e1_dgh_s2": dict(
            doc="EXPLOIT e1: argDGH only when s = 2; fully clears the tiny (8,9;2,2) w=27 table (1 survivor, W=150).",
            lean_body="if P.s = 2 then Prune.ofList P [counting P, argDGH P] else counting P",
            lean_doc="DGH restricted to s = 2",
            extra_py=DGH_PY, extra_return="(s == 2 and _dgh_kill(m, n, s, t, w, rows, cols))"),
        "e2_easy_certs": dict(
            doc="EXPLOIT e2: pool certificates whose every kill has d <= the table median (exactly-labelled "
                "tables only): kills only easy cases, broadly.",
            schema=sch(certs_of(easy_only))),
        "e3_relist": dict(
            doc="EXPLOIT e3: re-lists every library prune (argA, argAT, argD, argDT, deletion, waterfill, baseline, evolved).",
            lean_body="Prune.ofList P [counting P, argA P, argAT P, argD P, argDT P, countingA P, countingD P, "
                      "deletion P, argDelColWF P, argDelRowWF P, argWF P, baseline P, evolved P]",
            lean_doc="the proved library, re-listed"),
        "f_weak": dict(
            doc="general WEAK rule: the lowest-gain pool certificate of every (3,3) cell whose weakest certificate "
                "removes <= 16 % of the cell's work (one certificate per cell): small gains broadly.",
            schema=sch([weakest[k] for k in sorted(weakest)])),
    }
    for name, p in progs.items():
        src = build(name, p["doc"], p.get("lean_body", lib), p.get("lean_doc", "The evolved library."),
                    p.get("schema", sch([])), p.get("extra_py", ""), p.get("extra_return", ""))
        if p.get("lean_body") is None:  # keep the examplePrune def the library body refers to
            src = src.replace("LEAN_SOURCE = r'''\n", "LEAN_SOURCE = r'''\ndef examplePrune (P : Params) : Prune P where\n"
                              "  name := \"example (kills nothing)\"\n  kill := fun _ => false\n  sound := by intro A h; simp at h\n", 1)
        with open(os.path.join(OUT, f"{name}.py"), "w") as f:
            f.write(src)
        print(name, len(p.get("schema", sch([]))["farkas"]), "certs")
    for name in ("initial", "lean_dgh4", "schema_recipe", "instance_specific"):
        shutil.copy(os.path.join(ROOT, "tests", "candidates", f"{name}.py"), os.path.join(OUT, f"{name}.py"))
        print(name, "copied")


if __name__ == "__main__":
    main()
