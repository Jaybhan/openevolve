#!/usr/bin/env python3
"""Derive experiments/no_llm/config_stub.yaml from config.yaml: same prompt / database /
evaluator settings, LLM pointed at tools/stub_llm.py.  Re-run after config.yaml changes.

    python experiments/no_llm/make_config_stub.py [--port 8123] [--iterations 10] [--checkpoint-interval 5]
"""
import argparse
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
UB = os.path.abspath(os.path.join(HERE, "..", ".."))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8123)
    ap.add_argument("--iterations", type=int, default=10)
    ap.add_argument("--checkpoint-interval", type=int, default=5)
    ap.add_argument("--out", default=os.path.join(HERE, "config_stub.yaml"))
    a = ap.parse_args(argv)
    with open(os.path.join(UB, "config.yaml"), encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    cfg["llm"] = {"api_base": f"http://127.0.0.1:{a.port}/v1", "api_key": "x",
                  "models": [{"name": "stub-lean-bank", "weight": 1.0}],
                  "temperature": 0.0, "max_tokens": 8000, "timeout": 60, "retries": 1, "retry_delay": 1}
    cfg["max_iterations"] = a.iterations
    cfg["checkpoint_interval"] = a.checkpoint_interval
    header = ("# T-6 stub config (design §10.1): config.yaml with the LLM replaced by tools/stub_llm.py.\n"
              "# GENERATED by experiments/no_llm/make_config_stub.py -- re-run it after config.yaml changes.\n"
              "# Everything except `llm`, max_iterations and checkpoint_interval is copied from config.yaml.\n")
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=120))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
