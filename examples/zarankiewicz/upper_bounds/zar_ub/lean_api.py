"""Extract the public ZarPrune API (declaration signatures + doc comments) into
lean/API.md, and a compact one-line-per-item digest for LLM prompts.

  python -m zar_ub.lean_api            # writes lean/API.md and prints the digest
  python -m zar_ub api --docstring initial_program.py   # rewrites the LEAN API block of the docstring
"""
from __future__ import annotations

import os
import re
import textwrap
from typing import List, Tuple

_HERE = os.path.dirname(os.path.abspath(__file__))
LEAN_DIR = os.path.join(os.path.dirname(_HERE), "lean", "ZarPrune")
_DECL = re.compile(r"^(@\[[^\]]*\]\s*)?(private\s+)?(theorem|def|abbrev|structure|lemma|instance)\s+([\w.']+)")


def _statement(text: str) -> str:
    """Cut a declaration line at the first top-level ` := ` / `where` (a `:=` inside `{P with w := w'}`
    or a parenthesised default value does not end the statement)."""
    depth = 0
    i = 0
    while i < len(text):
        ch = text[i]
        if ch in "({[⟨":
            depth += 1
        elif ch in ")}]⟩":
            depth = max(0, depth - 1)
        elif depth == 0:
            if text.startswith(" := ", i) or text.endswith(" :=", ) and i == len(text) - 3:
                return text[:i].strip()
            if re.match(r"\swhere\b", text[i:]):
                return text[:i].strip()
        i += 1
    return text.strip()


def extract(path: str) -> List[Tuple[str, str, str]]:
    """Return (kind, name, signature) for each top-level declaration."""
    out = []
    lines = open(path).read().splitlines()
    i = 0
    in_comment = False
    while i < len(lines):
        l = lines[i]
        if in_comment:
            if "-/" in l:
                in_comment = False
            i += 1
            continue
        if l.lstrip().startswith("/-") and "-/" not in l:
            in_comment = True
            i += 1
            continue
        m = _DECL.match(l)
        if m and not m.group(2):
            kind, name = m.group(3), m.group(4)
            sig = [l]
            j = i + 1
            # collect until the first line that ends the statement (':=' or 'where' or a blank line)
            while j < len(lines) and not re.search(r"(:=|\bwhere\b)\s*(by)?\s*$", sig[-1]) and ":=" not in sig[-1] and lines[j].strip() and not _DECL.match(lines[j]):
                sig.append(lines[j]); j += 1
            text = " ".join(s.strip() for s in sig)
            text = _statement(text)
            if kind == "structure" or kind == "instance":
                text = " ".join(s.strip() for s in sig[:1])
            out.append((kind, name, re.sub(r"\s+", " ", text)))
        i += 1
    return out


def build(files: List[str] | None = None) -> Tuple[str, str]:
    files = files or sorted(f for f in os.listdir(LEAN_DIR) if f.endswith(".lean") and f != "Demo.lean")
    md = ["# ZarPrune API (auto-generated by zar_ub.lean_api)", ""]
    digest = []
    for f in files:
        items = extract(os.path.join(LEAN_DIR, f))
        md.append(f"## {f}\n")
        for kind, name, sig in items:
            md.append(f"- `{sig}`")
            digest.append(f"{name}: {sig.split(name, 1)[1].strip() if name in sig else sig}")
        md.append("")
    text = "\n".join(md)
    with open(os.path.join(os.path.dirname(LEAN_DIR), "API.md"), "w") as fh:
        fh.write(text + "\n")
    return text, "\n".join(digest)


